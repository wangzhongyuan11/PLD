"""Regenerate vivado/ps7_config.tcl from the seed tutorial tcl.

Extracts the processing_system7 set_property -dict block verbatim so the
PS7 config (MIO/DDR/clocks/AXI ports for PYNQ-Z2) stays diffable against
PYNQ_tutorials/dma/dma_tutorial.tcl without hand-copying ~770 properties.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "PYNQ_tutorials/dma/dma_tutorial.tcl"
DST = ROOT / "vivado/ps7_config.tcl"

def main():
    src = SRC.read_text(encoding="utf-8")
    m = re.search(
        r"# Create instance: processing_system7_0.*?\n(.*?)\n\s*\] \$processing_system7_0",
        src, re.S)
    assert m, "PS7 property block not found in seed tcl"
    block = "\n".join(
        line for line in m.group(1).splitlines()
        if "create_bd_cell" not in line
    )
    out = [
        "# PS7 configuration extracted mechanically from PYNQ_tutorials/dma/dma_tutorial.tcl",
        "# (generated by scripts/gen_ps7_config.py, do not hand-edit).",
        "proc apply_ps7_config {cell} {",
        block,
        " ] $cell",
        "}",
    ]
    DST.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {DST} with {len(re.findall(r'CONFIG[.]', block))} properties")

if __name__ == "__main__":
    main()
